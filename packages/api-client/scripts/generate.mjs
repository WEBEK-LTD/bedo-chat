// Generates src/generated.ts (typed API functions and types) from apps/api/openapi/openapi.json with orval.
//
//   node scripts/generate.mjs          write the file
//   node scripts/generate.mjs --check  fail if the committed file is out of date with the OpenAPI document
//
// The OpenAPI document is written by `pnpm --filter @bedo/api build` from the shared Zod contracts.
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { generate } from 'orval';

const root = path.dirname(fileURLToPath(new URL('../package.json', import.meta.url)));
const spec = path.join(root, '..', '..', 'apps', 'api', 'openapi', 'openapi.json');
const committed = path.join(root, 'src', 'generated.ts');
const check = process.argv.includes('--check');
const workDir = mkdtempSync(path.join(tmpdir(), 'bedo-api-client-'));
const target = path.join(workDir, 'generated.ts');

try {
  await generate(
    {
      input: { target: spec },
      output: {
        target,
        client: 'fetch',
        mode: 'single',
        prettier: false,
        override: {
          mutator: { path: path.join(root, 'src', 'transport.ts'), name: 'apiFetch' },
          fetch: { includeHttpResponseReturnType: false },
        },
      },
    },
    root,
  );
  const header = '// GENERATED FILE - do not edit. Run `pnpm --filter @bedo/api-client generate` after the API contracts change.\n';
  const output =
    header +
    readFileSync(target, 'utf8')
      // orval writes the mutator import relative to its temporary output folder.
      .replace(/from ['"][^'"]*transport(?:\.[jt]s)?['"]/g, "from './transport.js'")
      // orval stamps its version in the banner; keep the file stable across tool updates.
      .replace(/^\/\*\*\n \* Generated by orval[^]*?\*\/\n/, '');
  if (check) {
    const current = readFileSync(committed, 'utf8');
    if (current !== output) {
      console.error('src/generated.ts is out of date with apps/api/openapi/openapi.json. Run `pnpm --filter @bedo/api-client generate`.');
      process.exit(1);
    }
    console.log('src/generated.ts matches the OpenAPI document.');
  } else {
    writeFileSync(committed, output);
    console.log('Wrote src/generated.ts');
  }
} finally {
  rmSync(workDir, { recursive: true, force: true });
}
