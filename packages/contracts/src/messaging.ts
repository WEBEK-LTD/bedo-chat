import { z } from 'zod';
import { publicUserSchema } from './users.js';

/**
 * Phase 3 messaging rules: the values approved as D-30 (rate limits, P-16 to P-31) and the implementation
 * limits listed in docs/PHASE-3-REPORT.md. The API enforces them; the apps use them for their own checks.
 */
export const MESSAGING_RULES = {
  /** P-16 */
  textMaxLength: 4096,
  /** Rate limits (D-30): messages per user per minute; edits count, and so does every forwarded copy. */
  messagesPerMinute: 30,
  reportsPerDay: 20,
  /** P-27 */
  reportDetailsMaxLength: 500,
  /** P-17 */
  updateLogRetentionDays: 30,
  resyncThreshold: 1000,
  refetchPageSize: 50,
  /** Updates per sync response page. */
  syncPageSize: 200,
  /** P-18 */
  heartbeatSeconds: 25,
  onlineTtlSeconds: 60,
  typingSeconds: 6,
  /** P-19 */
  maxPinnedChats: 5,
  /** P-21 */
  maxFolders: 10,
  folderNameMaxLength: 12,
  maxChatsPerFolder: 200,
  /** P-23 */
  maxForwardTargets: 10,
  maxSelectedMessages: 100,
  /** P-25 */
  userSearchMinLength: 3,
  userSearchMaxLength: 64,
  userSearchLimit: 20,
  /** In-chat search (step 3.7). */
  chatSearchMaxLength: 100,
  chatSearchPageSize: 20,
  /** Characters of the replied-to message shown in a reply. */
  replyPreviewLength: 200,
  /** P-28 intake guard. */
  screenshotEventsPerHour: 60,
  /** Guard for actions that notify the other person (pin, unpin, block, unblock), per user per minute. */
  peerActionsPerMinute: 60,
  /** Guard for people search (P-25), per user per minute. */
  userSearchesPerMinute: 60,
} as const;

const uuid = z.string().uuid();
const seq = z.number().int().nonnegative();
const timestamp = z.string();

/** Length in characters (Unicode code points), as the database counts it, not UTF-16 units. */
export const characterCount = (text: string): number => Array.from(text).length;

/** Message text as sent: surrounding whitespace removed, 1 to 4,096 characters (P-16). */
export const messageTextSchema = z
  .string()
  .trim()
  .min(1)
  .refine((text) => characterCount(text) <= MESSAGING_RULES.textMaxLength, `at most ${MESSAGING_RULES.textMaxLength} characters`);

// ------------------------------------------------------------------------------------------- Users

/** Online state and last seen of another user; null when hidden (privacy Nobody, P-31, or a block). */
export const presenceSchema = z.object({
  online: z.boolean(),
  /** Rounded down to the minute (P-18); null while online or if never seen. */
  lastSeenAt: timestamp.nullable(),
});
export type Presence = z.infer<typeof presenceSchema>;

/**
 * Another user as the signed-in user may see them: the public profile (deleted accounts appear as
 * "Deleted account") with photo, phone and presence only where that user's privacy and blocks allow.
 */
export const peerSchema = publicUserSchema.extend({
  /** Only when that user's phone-number privacy is Everyone and no block applies. */
  phone: z.string().nullable(),
  presence: presenceSchema.nullable(),
  /** The signed-in user has blocked this user (P-30: the chat shows Unblock). */
  blockedByMe: z.boolean(),
  /**
   * Whether the signed-in user can send messages to this user now. False for a block in either direction,
   * "Who can message: Nobody", deleted accounts and the user's own blocked account; it never says which.
   */
  canMessage: z.boolean(),
});
export type Peer = z.infer<typeof peerSchema>;

export const userSearchQuerySchema = z.object({
  q: z.string().trim().min(MESSAGING_RULES.userSearchMinLength).max(MESSAGING_RULES.userSearchMaxLength),
});
export const userSearchResponseSchema = z.object({ users: z.array(peerSchema) });
export type UserSearchResponse = z.infer<typeof userSearchResponseSchema>;

// ---------------------------------------------------------------------------------------- Messages

export const replyPreviewSchema = z.object({
  id: z.string(),
  senderId: z.string(),
  /** Shortened text; null when the message was deleted or is hidden for the signed-in user. */
  text: z.string().nullable(),
});

export const forwardOriginSchema = z.object({
  id: z.string(),
  /** "Deleted account" for deleted accounts (P-23). */
  displayName: z.string(),
  deleted: z.boolean(),
});

export const messageSchema = z.object({
  id: z.string(),
  chatId: z.string(),
  seq,
  senderId: z.string(),
  clientId: z.string(),
  kind: z.literal('text'),
  /** Null once deleted for both sides. */
  text: z.string().nullable(),
  deleted: z.boolean(),
  replyTo: replyPreviewSchema.nullable(),
  forwardedFrom: forwardOriginSchema.nullable(),
  createdAt: timestamp,
  editedAt: timestamp.nullable(),
});
export type Message = z.infer<typeof messageSchema>;

export const sendMessageBodySchema = z.object({
  /** Generated by the app once per message and reused for every retry (never stores a duplicate). */
  clientId: uuid,
  text: messageTextSchema,
  replyToId: uuid.optional(),
});
export type SendMessageBody = z.infer<typeof sendMessageBodySchema>;

export const editMessageBodySchema = z.object({ text: messageTextSchema });
export type EditMessageBody = z.infer<typeof editMessageBodySchema>;

const selectedMessageIds = z
  .array(uuid)
  .min(1)
  .max(MESSAGING_RULES.maxSelectedMessages)
  .refine((ids) => new Set(ids).size === ids.length, 'message ids must be unique');

export const deleteMessagesBodySchema = z.object({
  chatId: uuid,
  messageIds: selectedMessageIds,
  /** "me": hide for the signed-in user only; "both": delete for both sides (sender only, P-29). */
  scope: z.enum(['me', 'both']),
});
export type DeleteMessagesBody = z.infer<typeof deleteMessagesBodySchema>;

export const forwardMessagesBodySchema = z.object({
  fromChatId: uuid,
  messageIds: selectedMessageIds,
  targets: z
    .array(z.object({ chatId: uuid, clientId: uuid }))
    .min(1)
    .max(MESSAGING_RULES.maxForwardTargets)
    .refine((targets) => new Set(targets.map((target) => target.chatId)).size === targets.length, 'chats must be unique')
    .refine((targets) => new Set(targets.map((target) => target.clientId)).size === targets.length, 'client ids must be unique'),
});
export type ForwardMessagesBody = z.infer<typeof forwardMessagesBodySchema>;

export const messagesResponseSchema = z.object({ messages: z.array(messageSchema) });
export type MessagesResponse = z.infer<typeof messagesResponseSchema>;

const seqParam = z.coerce.number().int().positive();
export const messageHistoryQuerySchema = z.object({
  /** Messages with a lower seq (older), newest first; or `after` for newer ones, oldest first. */
  before: seqParam.optional(),
  after: z.coerce.number().int().nonnegative().optional(),
  limit: z.coerce.number().int().min(1).max(MESSAGING_RULES.refetchPageSize).optional(),
});

export const chatSearchQuerySchema = z.object({
  q: z.string().trim().min(1).max(MESSAGING_RULES.chatSearchMaxLength),
  before: seqParam.optional(),
});

// ------------------------------------------------------------------------------------------- Chats

export const chatSchema = z.object({
  id: z.string(),
  type: z.literal('private'),
  peer: peerSchema,
  /** Newest message the signed-in user can see. */
  lastMessage: messageSchema.nullable(),
  lastSeq: seq,
  readSeq: seq,
  unreadCount: z.number().int().nonnegative(),
  markedUnread: z.boolean(),
  /** The other participant's positions, for the sent / delivered / seen status of one's own messages. */
  peerReadSeq: seq,
  peerDeliveredSeq: seq,
  pinned: z.boolean(),
  pinnedAt: timestamp.nullable(),
  archived: z.boolean(),
  folderIds: z.array(z.string()),
  createdAt: timestamp,
  lastMessageAt: timestamp.nullable(),
});
export type Chat = z.infer<typeof chatSchema>;

export const chatsResponseSchema = z.object({ chats: z.array(chatSchema) });
export type ChatsResponse = z.infer<typeof chatsResponseSchema>;

export const createChatBodySchema = z.object({ userId: uuid });

export const readChatBodySchema = z.object({ seq });

export const chatStateBodySchema = z
  .object({
    pinned: z.boolean().optional(),
    archived: z.boolean().optional(),
    /** true: mark as unread; false: clear the mark (reading the chat also clears it). */
    unread: z.boolean().optional(),
  })
  .refine((body) => Object.keys(body).length > 0, 'nothing to update');

// ----------------------------------------------------------------------------------------- Folders

export const folderNameSchema = z
  .string()
  .trim()
  .min(1)
  .refine((name) => characterCount(name) <= MESSAGING_RULES.folderNameMaxLength, `at most ${MESSAGING_RULES.folderNameMaxLength} characters`);
const folderChatIds = z
  .array(uuid)
  .max(MESSAGING_RULES.maxChatsPerFolder)
  .refine((ids) => new Set(ids).size === ids.length, 'chats must be unique');

export const folderSchema = z.object({ id: z.string(), name: z.string(), chatIds: z.array(z.string()) });
export type Folder = z.infer<typeof folderSchema>;
export const foldersResponseSchema = z.object({ folders: z.array(folderSchema) });
export const createFolderBodySchema = z.object({ name: folderNameSchema, chatIds: folderChatIds.default([]) });
export const updateFolderBodySchema = z
  .object({ name: folderNameSchema.optional(), chatIds: folderChatIds.optional() })
  .refine((body) => Object.keys(body).length > 0, 'nothing to update');

// ---------------------------------------------------------------------------------------- Safety

export const REPORT_REASONS = ['spam', 'harassment', 'inappropriate_content', 'other'] as const;
export const reportBodySchema = z.object({
  userId: uuid,
  /** Report one message of that user (from a chat the signed-in user is in). */
  messageId: uuid.optional(),
  reason: z.enum(REPORT_REASONS),
  details: z
    .string()
    .trim()
    .min(1)
    .refine((text) => characterCount(text) <= MESSAGING_RULES.reportDetailsMaxLength, `at most ${MESSAGING_RULES.reportDetailsMaxLength} characters`)
    .optional(),
});
export type ReportBody = z.infer<typeof reportBodySchema>;

/** P-28: sent by the iOS and Android apps only (Phase 12); refused from every other platform. */
export const screenshotEventBodySchema = z.object({
  chatId: uuid.optional(),
  screen: z.string().regex(/^[a-z_]{1,40}$/),
  messageIds: z.array(uuid).max(MESSAGING_RULES.maxSelectedMessages).optional(),
  occurredAt: z.iso.datetime({ offset: true }),
});

// ------------------------------------------------------------------------------------------- Sync

/** Kinds of entries in a user's update log (P-17). */
export const UPDATE_KINDS = [
  'message.new',
  'message.edited',
  /** Deleted for both sides. */
  'message.deleted',
  /** Deleted for the signed-in user only. */
  'message.hidden',
  'message.pinned',
  'message.unpinned',
  /** A member's read position moved (data: userId, seq). */
  'chat.read',
  /** A member's delivered position moved (data: userId, seq). */
  'chat.delivered',
  /** The signed-in user's pinned / archived / unread state of a chat changed. */
  'chat.state',
  'folders',
  /** The signed-in user blocked or unblocked someone (data: userId, blocked). */
  'block',
] as const;
export type UpdateKind = (typeof UPDATE_KINDS)[number];

export const updateSchema = z.object({
  seq,
  kind: z.enum(UPDATE_KINDS),
  chatId: z.string().nullable(),
  messageId: z.string().nullable(),
  data: z.record(z.string(), z.unknown()),
});
export type Update = z.infer<typeof updateSchema>;

export const syncQuerySchema = z.object({ since: z.coerce.number().int().nonnegative() });

export const syncResponseSchema = z.object({
  /** The highest update seq included; the next request asks for updates after it. */
  seq,
  updates: z.array(updateSchema),
  hasMore: z.boolean(),
  /**
   * The device is too far behind (more than 1,000 updates, or older than the 30-day log): it must
   * re-fetch its chats and their messages page by page, then continue from `seq` (P-17).
   */
  resync: z.boolean(),
  /** Current state of every chat the updates touch. */
  chats: z.array(chatSchema),
  /** Current state of every message the updates touch and the user can still see. */
  messages: z.array(messageSchema),
  /** The user's folders, when the updates include a folder change. */
  folders: z.array(folderSchema).nullable(),
});
export type SyncResponse = z.infer<typeof syncResponseSchema>;

// --------------------------------------------------------------------------------------- Realtime

/**
 * Realtime (D-36). The API runs in the website's server functions, which cannot hold connections open, so
 * devices listen on Supabase Realtime: each signed-in device gets its own private broadcast channel (a name
 * derived from its session and the current hour with a server secret, never guessable) and receives short
 * signals on it. Signals carry no message content: "updates" tells the device to fetch its new updates over
 * HTTP (permission-checked like every request); typing and presence are sent only where the permission service
 * allows. Devices send their heartbeat, typing and going offline over HTTP.
 */
export const REALTIME_SIGNAL_EVENT = 'signal';

export const realtimeSignalSchema = z.discriminatedUnion('type', [
  /** The user's update log moved on: fetch GET /v1/sync. */
  z.object({ type: z.literal('updates') }),
  z.object({ type: z.literal('typing'), chatId: z.string(), userId: z.string() }),
  z.object({ type: z.literal('presence'), userId: z.string(), presence: presenceSchema.nullable() }),
]);
export type RealtimeSignal = z.infer<typeof realtimeSignalSchema>;

/** Where this device listens. `enabled` is false when realtime is not configured: devices then poll. */
export const realtimeChannelResponseSchema = z.object({
  enabled: z.boolean(),
  /** Supabase project URL (https://<project>.supabase.co). */
  url: z.string().nullable(),
  /** The project's public (anon) key; with public access turned off it grants no channel on its own. */
  apiKey: z.string().nullable(),
  /**
   * This device's realtime token (a short-lived JWT): it may receive on `topic` and nowhere else, and send nothing.
   * Valid until a few minutes after `expiresAt`.
   */
  accessToken: z.string().nullable(),
  /** This device's private channel name. */
  topic: z.string().nullable(),
  /** When the name changes (every hour): the device asks for the new one then. */
  expiresAt: z.string().nullable(),
  /**
   * Seconds until then, by the server's clock: the device schedules the change from this, so a wrong clock on the
   * device cannot make it keep an expired token or ask for a new one in a loop.
   */
  expiresInSeconds: z.number().int().nonnegative().nullable(),
  event: z.literal(REALTIME_SIGNAL_EVENT),
  /** Send POST /v1/realtime/heartbeat this often (P-18). */
  heartbeatSeconds: z.number().int().positive(),
});
export type RealtimeChannelResponse = z.infer<typeof realtimeChannelResponseSchema>;

/** Heartbeat answer: the user's current update seq, so a device that missed a signal catches up. */
export const realtimeHeartbeatResponseSchema = z.object({ seq });
export type RealtimeHeartbeatResponse = z.infer<typeof realtimeHeartbeatResponseSchema>;

/** The user is typing in a chat; lasts 6 seconds unless sent again (P-18). */
export const realtimeTypingBodySchema = z.object({ chatId: uuid });
