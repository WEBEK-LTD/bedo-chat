/** Rules for the one-time initial setup and the OTP settings. */
export const ADMIN_BOOTSTRAP_RULES = {
  /** Wrong setup tokens before the token stops working (the owner then issues a new one by SQL). */
  maxFailedTokenAttempts: 5,
  /** Initial-setup requests per IP address per 15 minutes. */
  maxRequestsPerIp: 20,
  ipWindowSeconds: 15 * 60,
  /** Test messages per admin (or during setup) per 15 minutes. */
  maxTestMessages: 5,
  testMessageWindowSeconds: 15 * 60,
  /** How long the API waits for the worker to report a test message's result. */
  testMessageTimeoutSeconds: 30,
} as const;

/**
 * A Waabek API key as typed into the Admin Dashboard: printable characters without spaces. The value is
 * never echoed in validation errors.
 */
export const waabekApiKeySchema = z
  .string()
  .trim()
  .min(8, 'must be at least 8 characters')
  .max(512, 'must be at most 512 characters')
  .regex(/^[\x21-\x7e]+$/, 'must contain only letters, digits and symbols, without spaces');

export const setupTokenSchema = z.string().trim().min(20).max(200);

/** Rules for the owner-only Waabek key recovery (D-33). */
export const OTP_RECOVERY_RULES = {
  maxFailedTokenAttempts: 5,
  maxRequestsPerIp: 20,
  ipWindowSeconds: 15 * 60,
} as const;
export const otpRecoveryStatusResponseSchema = z.object({
  /** Whether the owner has opened a Waabek key recovery by SQL (not expired, not locked). */
  recoveryOpen: z.boolean(),
});
export const otpRecoveryWaabekKeyBodySchema = z.object({ recoveryToken: setupTokenSchema, apiKey: waabekApiKeySchema });
export const otpRecoveryTestBodySchema = z.object({ recoveryToken: setupTokenSchema });

export const adminBootstrapStatusResponseSchema = z.object({
  /** Whether the initial setup is open (opened by SQL, not expired, not locked, not completed). */
  setupOpen: z.boolean(),
});
export const adminBootstrapWaabekKeyBodySchema = z.object({ setupToken: setupTokenSchema, apiKey: waabekApiKeySchema });
export const adminBootstrapTestBodySchema = z.object({ setupToken: setupTokenSchema });

/** Why a test message was not delivered. */
export const otpDeliveryFailureSchema = z.enum(['not_configured', 'key_unreadable', 'rejected', 'unreachable', 'no_answer']);
export type OtpDeliveryFailure = z.infer<typeof otpDeliveryFailureSchema>;

export const waabekTestResponseSchema = z.object({
  delivered: z.boolean(),
  /** The number the test message was sent to, partly hidden. */
  sentTo: z.string(),
  reason: otpDeliveryFailureSchema.nullable(),
  /** Waabek's HTTP status when it refused the message (for example 401 for a wrong key). */
  httpStatus: z.number().int().nullable(),
});
export type WaabekTestResponse = z.infer<typeof waabekTestResponseSchema>;

export const otpSettingsResponseSchema = z.object({
  provider: z.literal('waabek'),
  /** Whether a Waabek API key is stored. The key itself is never returned. */
  apiKeyConfigured: z.boolean(),
  /** Raised on every change. */
  version: z.number().int(),
  updatedAt: z.string().nullable(),
  /** Who set the key; null when it was set during the initial setup or an owner recovery, or never set. */
  updatedBy: z.object({ id: z.string(), name: z.string() }).nullable(),
  /** How the key was last set (D-33 adds owner recovery). */
  updatedVia: z.enum(['initial_setup', 'admin_dashboard', 'owner_recovery']).nullable(),
});
export const otpSettingsReplaceKeyBodySchema = z.object({
  apiKey: waabekApiKeySchema,
  /** A current authenticator code: replacing the key needs a fresh confirmation. */
  totpCode: z.string().regex(/^\d{6}$/, 'must be 6 digits'),
});
export const otpSettingsReplaceKeyResponseSchema = z.object({ saved: z.literal(true), version: z.number().int() });

/** Shows a phone number with the middle digits hidden: +905******942. */
export function maskPhone(phone: string): string {
  return phone.length <= 7 ? '***' : `${phone.slice(0, 4)}${'*'.repeat(phone.length - 7)}${phone.slice(-3)}`;
}
