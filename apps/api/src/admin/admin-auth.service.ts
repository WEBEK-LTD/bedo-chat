import { HttpStatus, Inject, Injectable } from '@nestjs/common';
import type { ApiEnv } from '@bedo/config';
import { ADMIN_SESSION_RULES, type AdminInfo, TOKEN_RULES } from '@bedo/contracts';
import type { AdminRole } from '@bedo/db';
import { sql } from 'kysely';
import { AppError } from '../common/app-error.js';
import { hashToken, randomToken } from '../common/crypto.js';
import type { RequestInfo } from '../common/request-info.js';
import { API_ENV } from '../config/tokens.js';
import { AuditService } from '../audit/audit.service.js';
import { DatabaseService } from '../database/database.service.js';
import { EphemeralStore } from '../state/ephemeral.store.js';
import { RateLimitService } from '../state/rate-limit.service.js';
import { AdminBootstrapService } from './admin-bootstrap.service.js';
import { base32Encode, decryptSecret, encryptSecret, generateTotpSecret, otpauthUri, TOTP_ISSUER, verifyTotp } from './totp.js';

const DAY_MS = 24 * 60 * 60 * 1000;

export interface AdminContext {
  adminId: string;
  sessionId: string;
  role: AdminRole;
  name: string;
}

interface PendingAdmin {
  adminId: string;
  /**
   * Phase 3.1: the account has no authenticator yet (created by SQL). This sign-in must set one up: the
   * secret is generated by the server, kept (encrypted with ADMIN_TOTP_KEY) with the pending sign-in, and
   * written to the account only after the admin confirms it with a code.
   */
  enrol?: true;
  /**
   * D-34: when the password that started this sign-in was set. If the password is reset or changed before the
   * authenticator step completes, the pending sign-in is refused.
   */
  passwordChangedAt: string;
}

function passwordStamp(value: Date | null): string {
  return value ? new Date(value).toISOString() : 'none';
}

export type AdminPendingSignIn = { status: 'totp_required' | 'totp_setup_required'; pendingToken: string };

/**
 * Admin sign-in (D-19 as amended by D-34, P-13): phone and password (AdminPasswordService), then a mandatory
 * authenticator-app code; no admin session exists without it. Admin accounts and sessions are separate from
 * student accounts and sessions. WhatsApp codes are not part of admin sign-in.
 */
@Injectable()
export class AdminAuthService {
  private readonly totpKey: Buffer;

  constructor(
    @Inject(API_ENV) env: ApiEnv,
    @Inject(DatabaseService) private readonly database: DatabaseService,
    @Inject(EphemeralStore) private readonly store: EphemeralStore,
    @Inject(RateLimitService) private readonly rateLimit: RateLimitService,
    @Inject(AuditService) private readonly audit: AuditService,
    @Inject(AdminBootstrapService) private readonly bootstrap: AdminBootstrapService,
  ) {
    this.totpKey = Buffer.from(env.ADMIN_TOTP_KEY, 'base64');
  }

  private get db() {
    return this.database.db;
  }

  /**
   * After a correct password (D-34): starts the authenticator step. An account without an authenticator
   * (created by SQL) must set one up first (Phase 3.1). Returns the short-lived pending sign-in token.
   */
  async startPendingSignIn(admin: { id: string; totp_secret_enc: string | null; password_changed_at: Date | null }): Promise<AdminPendingSignIn> {
    const pendingToken = randomToken();
    const enrol = admin.totp_secret_enc === null;
    const stamp = passwordStamp(admin.password_changed_at);
    const pending: PendingAdmin = enrol ? { adminId: admin.id, enrol: true, passwordChangedAt: stamp } : { adminId: admin.id, passwordChangedAt: stamp };
    await this.store.set(
      this.pendingKey(pendingToken),
      JSON.stringify(pending),
      (enrol ? ADMIN_SESSION_RULES.enrolmentSeconds : ADMIN_SESSION_RULES.pendingTokenSeconds) * 1000,
    );
    return { status: enrol ? 'totp_setup_required' : 'totp_required', pendingToken };
  }

  /**
   * First-time authenticator setup (Phase 3.1), after the password (D-34): returns the secret generated for
   * this sign-in attempt (the same one on every call), for the QR code and manual entry. Nothing is written
   * to the account until the admin confirms a code with POST totp/verify.
   */
  async setupTotp(pendingToken: string, info: RequestInfo): Promise<{ otpauthUri: string; setupKey: string; issuer: string; accountName: string }> {
    const pending = await this.readPending(pendingToken);
    if (!pending?.enrol) {
      throw new AppError(HttpStatus.UNAUTHORIZED, 'SESSION_INVALID');
    }
    const admin = await this.db.selectFrom('app.admin_accounts').selectAll().where('id', '=', pending.adminId).executeTakeFirst();
    if (!admin || admin.status !== 'active' || admin.totp_secret_enc !== null || !this.passwordStillValid(admin, pending)) {
      throw new AppError(HttpStatus.UNAUTHORIZED, 'SESSION_INVALID');
    }
    const ttlMs = await this.store.ttlMs(this.pendingKey(pendingToken));
    if (ttlMs === null) {
      throw new AppError(HttpStatus.UNAUTHORIZED, 'SESSION_INVALID');
    }
    // One secret per sign-in attempt, even if the page asks twice at the same time.
    const created = await this.store.setIfAbsent(this.enrolmentKey(pendingToken), encryptSecret(this.totpKey, generateTotpSecret()), ttlMs);
    const stored = await this.store.get(this.enrolmentKey(pendingToken));
    if (!stored) {
      throw new AppError(HttpStatus.UNAUTHORIZED, 'SESSION_INVALID');
    }
    if (created) {
      await this.audit.security(this.db, {
        subjectType: 'admin',
        subjectId: admin.id,
        event: 'admin_totp_setup_started',
        ip: info.ip,
        userAgent: info.userAgent,
      });
    }
    const secret = decryptSecret(this.totpKey, stored);
    return { otpauthUri: otpauthUri(secret, admin.phone), setupKey: base32Encode(secret), issuer: TOTP_ISSUER, accountName: admin.phone };
  }

  private async readPending(pendingToken: string): Promise<PendingAdmin | null> {
    const raw = await this.store.get(this.pendingKey(pendingToken));
    return raw ? (JSON.parse(raw) as PendingAdmin) : null;
  }

  async verifyTotp(pendingToken: string, code: string, info: RequestInfo): Promise<{ admin: AdminInfo; sessionToken: string }> {
    const pending = await this.readPending(pendingToken);
    if (!pending) {
      throw new AppError(HttpStatus.UNAUTHORIZED, 'SESSION_INVALID');
    }
    // Counted before the code is checked, so parallel guesses cannot share one count (P-13).
    const attempt = await this.rateLimit.reserveAttempt(this.attemptsKey(pendingToken), ADMIN_SESSION_RULES.enrolmentSeconds * 1000);
    if (attempt.count > TOKEN_RULES.maxTwoStepPasswordAttempts) {
      await this.store.delete(this.pendingKey(pendingToken), this.enrolmentKey(pendingToken));
      throw new AppError(HttpStatus.UNAUTHORIZED, 'SESSION_INVALID');
    }
    const admin = await this.db.selectFrom('app.admin_accounts').selectAll().where('id', '=', pending.adminId).executeTakeFirst();
    if (!admin || admin.status !== 'active' || !this.passwordStillValid(admin, pending)) {
      throw new AppError(HttpStatus.UNAUTHORIZED, 'SESSION_INVALID');
    }
    // Phase 3.1: an account without an authenticator confirms the secret generated by setupTotp.
    const enrolmentSecretEnc = pending.enrol ? await this.store.get(this.enrolmentKey(pendingToken)) : null;
    const secretEnc = pending.enrol ? enrolmentSecretEnc : admin.totp_secret_enc;
    if (!secretEnc || (pending.enrol && admin.totp_secret_enc !== null)) {
      throw new AppError(HttpStatus.UNAUTHORIZED, 'SESSION_INVALID');
    }
    const lastStep = admin.totp_last_step === null ? null : Number(admin.totp_last_step);
    const step = verifyTotp(decryptSecret(this.totpKey, secretEnc), code, Date.now(), lastStep);
    if (step === null) {
      if (attempt.count >= TOKEN_RULES.maxTwoStepPasswordAttempts) {
        await this.store.delete(this.pendingKey(pendingToken), this.enrolmentKey(pendingToken));
      }
      await this.audit.security(this.db, {
        subjectType: 'admin',
        subjectId: admin.id,
        event: 'admin_totp_failed',
        ip: info.ip,
        userAgent: info.userAgent,
        details: { attempts: attempt.count, ...(pending.enrol ? { setup: true } : {}) },
      });
      throw new AppError(HttpStatus.BAD_REQUEST, 'TOTP_INVALID');
    }
    // Only one request can consume the pending sign-in.
    if ((await this.store.delete(this.pendingKey(pendingToken))) !== 1) {
      throw new AppError(HttpStatus.UNAUTHORIZED, 'SESSION_INVALID');
    }
    await this.store.delete(this.enrolmentKey(pendingToken));

    const sessionToken = randomToken();
    await this.db.transaction().execute(async (trx) => {
      // The step update only succeeds if no other sign-in used this or a later step meanwhile (no replay).
      // A first-time setup stores the confirmed secret, and only where the account still has none.
      const confirming = !admin.totp_confirmed_at;
      const updated = await trx
        .updateTable('app.admin_accounts')
        .set({
          totp_last_step: step,
          ...(pending.enrol ? { totp_secret_enc: secretEnc } : {}),
          ...(confirming ? { totp_confirmed_at: sql`now()` } : {}),
        })
        .where('id', '=', admin.id)
        .where((eb) => eb.or([eb('totp_last_step', 'is', null), eb('totp_last_step', '<', String(step))]))
        .where((eb) => (pending.enrol ? eb('totp_secret_enc', 'is', null) : eb('totp_secret_enc', 'is not', null)))
        .executeTakeFirst();
      if (Number(updated.numUpdatedRows) !== 1) {
        throw new AppError(HttpStatus.BAD_REQUEST, 'TOTP_INVALID');
      }
      if (pending.enrol) {
        await this.audit.security(trx, {
          subjectType: 'admin',
          subjectId: admin.id,
          event: 'admin_totp_enrolled',
          ip: info.ip,
          userAgent: info.userAgent,
        });
        await this.audit.admin(trx, { adminId: admin.id, action: 'admin.totp_enrolled', ip: info.ip, userAgent: info.userAgent });
      }
      // The first Super Admin with a confirmed authenticator closes the initial setup for good (Phase 3.1).
      if (confirming && admin.role === 'super_admin' && (await this.bootstrap.closeIfOpen(trx, admin.id))) {
        await this.audit.admin(trx, {
          adminId: admin.id,
          action: 'admin.bootstrap_closed',
          targetType: 'admin_bootstrap',
          ip: info.ip,
          userAgent: info.userAgent,
        });
      }
      const session = await trx
        .insertInto('app.admin_sessions')
        .values({
          admin_id: admin.id,
          token_hash: hashToken(sessionToken),
          expires_at: new Date(Date.now() + ADMIN_SESSION_RULES.sessionDays * DAY_MS),
          ip: info.ip,
          user_agent: info.userAgent,
        })
        .returning('id')
        .executeTakeFirstOrThrow();
      await this.audit.security(trx, {
        subjectType: 'admin',
        subjectId: admin.id,
        event: 'admin_login_succeeded',
        sessionId: session.id,
        ip: info.ip,
        userAgent: info.userAgent,
      });
      await this.audit.admin(trx, { adminId: admin.id, action: 'admin.signed_in', ip: info.ip, userAgent: info.userAgent });
    });
    return { admin: { id: admin.id, name: admin.name, role: admin.role }, sessionToken };
  }

  /** Session check on every admin request (D-49): a session in use is renewed, so an admin stays signed in. */
  async authenticate(sessionToken: string): Promise<AdminContext> {
    const row = await this.db
      .selectFrom('app.admin_sessions')
      .innerJoin('app.admin_accounts', 'app.admin_accounts.id', 'app.admin_sessions.admin_id')
      .select([
        'app.admin_sessions.id as session_id',
        'app.admin_sessions.last_active_at',
        'app.admin_sessions.revoked_at',
        'app.admin_accounts.id as admin_id',
        'app.admin_accounts.name',
        'app.admin_accounts.role',
        'app.admin_accounts.status',
      ])
      .where('app.admin_sessions.token_hash', '=', hashToken(sessionToken))
      .executeTakeFirst();
    const now = Date.now();
    if (
      !row ||
      row.revoked_at ||
      row.status !== 'active' ||
      // Renewed by use (D-49): last_active_at moves forward at most once a minute, so the session lasts 400 days
      // from the last use rather than from the sign-in (expires_at only records the first 400 days).
      now - new Date(row.last_active_at).getTime() > ADMIN_SESSION_RULES.sessionDays * DAY_MS
    ) {
      throw new AppError(HttpStatus.UNAUTHORIZED, 'UNAUTHENTICATED');
    }
    if (now - new Date(row.last_active_at).getTime() > 60_000) {
      await this.db.updateTable('app.admin_sessions').set({ last_active_at: sql`now()` }).where('id', '=', row.session_id).execute();
    }
    return { adminId: row.admin_id, sessionId: row.session_id, role: row.role, name: row.name };
  }

  async logout(context: AdminContext, info: RequestInfo): Promise<void> {
    await this.db.transaction().execute(async (trx) => {
      await trx.updateTable('app.admin_sessions').set({ revoked_at: sql`now()` }).where('id', '=', context.sessionId).execute();
      await this.audit.admin(trx, { adminId: context.adminId, action: 'admin.signed_out', ip: info.ip, userAgent: info.userAgent });
    });
  }

  private pendingKey(token: string): string {
    return `admin-pending:${hashToken(token)}`;
  }

  /** D-34: the account still has the password that started this sign-in (not reset or changed since). */
  private passwordStillValid(admin: { password_hash: string | null; password_changed_at: Date | null }, pending: PendingAdmin): boolean {
    return admin.password_hash !== null && passwordStamp(admin.password_changed_at) === pending.passwordChangedAt;
  }

  private enrolmentKey(token: string): string {
    return `admin-pending-enrolment:${hashToken(token)}`;
  }

  private attemptsKey(token: string): string {
    return `admin-pending-attempts:${hashToken(token)}`;
  }
}
